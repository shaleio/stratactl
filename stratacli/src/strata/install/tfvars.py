"""Generate Terraform/OpenTofu variable files from the installation config.

The installation config (strata.yaml) is the source of truth; this module renders
it into HCL. Only fields with a ``tfvar`` name are emitted, grouped by section
with comment headers. Values come from the config; a field absent from the config
falls back to its schema default. Empty optional strings are skipped to keep the
output clean, while required fields and lists/bools are always emitted.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from strata.install.schema import Field, InstallSchema
from strata.install import store

GENERATED_HEADER = (
    "# GENERATED by `strata init` — do not edit by hand.\n"
    "# Edit strata.yaml (the source of truth) and re-run `strata init`.\n\n"
)


def _hcl_scalar(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    return '"' + str(value).replace("\\", "\\\\").replace('"', '\\"') + '"'


def hcl_value(field: Field, value: Any) -> str:
    if field.type == "list":
        items = value if isinstance(value, list) else ([] if value in (None, "") else [value])
        return "[" + ", ".join(_hcl_scalar(v) for v in items) + "]"
    if field.type == "bool":
        return "true" if bool(value) else "false"
    if field.type == "int":
        return str(int(value))
    return _hcl_scalar(value)


def _resolve(field: Field, config: dict[str, Any]) -> Any:
    val = store.get(config, field.section, field.key, None)
    if val is None:
        val = field.default
    return val


def _emit(field: Field, value: Any) -> bool:
    """Whether to write this field. Always emit required, bools, and lists;
    skip optional empty strings/None to keep tfvars tidy."""
    if field.required or field.type in ("bool", "list", "int"):
        return value is not None
    return value not in (None, "")


def render(schema: InstallSchema, config: dict[str, Any]) -> str:
    lines: list[str] = [GENERATED_HEADER.rstrip("\n")]
    for section in schema.sections():
        section_fields = [
            f for f in schema.fields
            if f.section == section and f.tfvar
        ]
        rendered: list[str] = []
        for f in section_fields:
            value = _resolve(f, config)
            if not _emit(f, value):
                continue
            rendered.append(f"{f.tfvar} = {hcl_value(f, value)}")
        if rendered:
            lines.append("")
            lines.append(f"# ---- {section} ----")
            lines.extend(rendered)
    return "\n".join(lines) + "\n"


def write(schema: InstallSchema, config: dict[str, Any],
          out_dir: Path, filename: str = "terraform.tfvars") -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / filename
    path.write_text(render(schema, config), encoding="utf-8")
    return path


def render_module(schema: InstallSchema, config: dict[str, Any], module_id: str) -> str:
    """Render only a module's fields (stored under its module section) for a
    module-specific *.auto.tfvars file."""
    section = store.module_section(module_id)
    lines = [GENERATED_HEADER.rstrip("\n"), "", f"# ---- module: {module_id} ----"]
    any_field = False
    for f in schema.tfvar_fields():
        value = store.get(config, section, f.key, f.default)
        if not _emit(f, value):
            continue
        lines.append(f"{f.tfvar} = {hcl_value(f, value)}")
        any_field = True
    if not any_field:
        return ""
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------- #
# JSON rendering — for the StrataCI runner. The CLI uploads the result as an
# *.auto.tfvars.json file the runner drops next to the module's tofu, so a customer's
# `strata init` values reach the ephemeral build (which never sees strata.yaml).
# --------------------------------------------------------------------------- #
def _native_value(field: Field, value: Any) -> Any:
    """Coerce to a native JSON type (bool/int/list/str) rather than an HCL string."""
    if field.type == "list":
        return value if isinstance(value, list) else ([] if value in (None, "") else [value])
    if field.type == "bool":
        return bool(value)
    if field.type == "int":
        return int(value)
    return value


def render_json(schema: InstallSchema, config: dict[str, Any]) -> dict[str, Any]:
    """Render the deployment config as a {tfvar: native_value} dict (JSON tfvars)."""
    out: dict[str, Any] = {}
    for section in schema.sections():
        for f in schema.fields:
            if f.section != section or not f.tfvar:
                continue
            value = _resolve(f, config)
            if not _emit(f, value):
                continue
            out[f.tfvar] = _native_value(f, value)
    return out


def render_module_json(schema: InstallSchema, config: dict[str, Any], module_id: str) -> dict[str, Any]:
    """render_json for a module whose values live under its module section."""
    section = store.module_section(module_id)
    out: dict[str, Any] = {}
    for f in schema.tfvar_fields():
        value = store.get(config, section, f.key, f.default)
        if not _emit(f, value):
            continue
        out[f.tfvar] = _native_value(f, value)
    return out
